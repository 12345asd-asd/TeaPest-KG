def build():
    rows = []
    for (qid, qtype, question, ctx, groups, need, kg_ans, src, gold) in Q:
        # gold_groups 统一两层结构 [[组0的若干OR正则], [组1...]]；
        # ban 题元组里给的是单组的 pattern 列表，这里包一层。
        if qtype == "ban":
            groups = [groups]
        assert all(isinstance(g, list) for g in groups), qid
        assert need <= len(groups), qid
        rows.append({
            "id": qid, "stratum": "external", "type": qtype,
            "difficulty": "hard" if qtype in ("threshold", "interval", "ban") else "medium",
            "hops": 0, "question": question, "context_entity": ctx,
            "answer_list": [], "expected": "answer",
            "gold_source": src, "gold_text": gold,
            "gold_groups": groups, "need": need,
            "kg_answerable": kg_ans,
        })
    ids = [r["id"] for r in rows]
    assert len(ids) == len(set(ids))
    json.dump(rows, open(OUT_JSON, "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    from collections import Counter
    tc = Counter(r["type"] for r in rows)
    kc = Counter("kg可答" if r["kg_answerable"] else "KG外" for r in rows)
    L = ["TeaPest-QA-External  共 %d 题（独立手册，破循环性）" % len(rows), "=" * 78]
    for r in rows:
        L.append("[%s|%s|%s] %s" % (r["id"], r["type"],
                                    "KG可答" if r["kg_answerable"] else "KG外",
                                    r["question"]))
        L.append("     gold: %s" % r["gold_text"])
        L.append("     src : %s" % r["gold_source"])
    L.append("=" * 78)
    L.append("题型: " + dict.__repr__(dict(tc)))
    L.append("覆盖: " + dict.__repr__(dict(kc)))
    open(OUT_TXT, "w", encoding="utf-8").write("\n".join(L))
    print("n=%d" % len(rows), dict(tc), dict(kc))
    print("->", OUT_JSON)


if __name__ == "__main__":
    build()
